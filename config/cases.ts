/**
 * 성공사례 Source of Truth
 *
 * ⚠️ 왜 배열이 비어 있는가 (임의 삭제하지 말 것)
 * 리뉴얼 전 사이트에는 같은 사례가 위치마다 다른 숫자로 실려 있었다.
 *  - 의류 쇼핑몰: 홈 "매출 +1,850만원(13배)" vs /cases "매출 +210%"
 *  - 세 번째 사례: 홈 "마케팅 툴 23위→2위" vs /cases "SaaS 32위→5위"
 *  - 광고 문구: "42위→3위" (홈·/cases 어디에도 없는 네 번째 버전)
 * 어느 값이 맞는지 판단할 수 있는 원본이 리포지토리에 없다. 임의로 하나를 고르거나
 * 병합하면 확인되지 않은 성과 수치를 사실로 표시하게 되므로, 값이 확정될 때까지 표시하지 않는다.
 *
 * ✅ 채우는 방법
 * 아래 CaseStudy 형식에 맞춰 실제 작업 기록(주문 내역·순위 추적 스냅샷)에서 확인된 사례만 추가하면
 * /cases 페이지와 홈 사례 프리뷰에 자동으로 렌더링된다. 한 건만 넣어도 동작한다.
 */

export type CaseStudy = {
  id: string
  /** 업종 */
  industry: string
  /** 목표 (키워드 또는 목표 페이지) */
  target: string
  /** 작업 전 상태 — 확인 가능한 값만 */
  before: string
  /** 작업 후 상태 */
  after: string
  /** 기간 */
  period: string
  /** 진행한 작업 */
  work: string[]
  /** 어떤 문제였는가 */
  problem: string
  /** 초기 상태 판단 */
  diagnosis: string
  /** 무엇을 근거로 그렇게 판단했는가 */
  reasoning: string
  /** 결과 해석 */
  interpretation: string
  /** 한계 또는 주의점 — 반드시 채운다 */
  caveat: string
  /** 수치의 측정 기준 (기간·도구·표본). 비어 있으면 수치를 표시하지 않는다. */
  measurement: string
}

