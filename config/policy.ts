export const POLICY_DOCUMENTS: PolicyDocument[] = [TERMS, PRIVACY, REFUND]

export function getPolicy(slug: PolicyDocument['slug']): PolicyDocument {
  return POLICY_DOCUMENTS.find(doc => doc.slug === slug) as PolicyDocument
}

export function otherPolicies(slug: PolicyDocument['slug']) {
  return POLICY_DOCUMENTS.filter(doc => doc.slug !== slug).map(doc => ({
    href: `/${doc.slug}`,
    label: doc.title,
  }))
}
